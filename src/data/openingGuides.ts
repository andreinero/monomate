// ───────────────────────────── Language-aware prose ─────────────────────────────
// The prose fields above are English. When the app language is German and a German
// entry exists (./openingGuides.de.ts, keyed by id), these getters return the German text
// instead. Read at access time, so switching language takes effect without a reload.
// `id`, `name` (matched against game openings), `eco`, `side`, `level`, `group` and all
// move strings stay as they are.

function localize<T extends object, K extends keyof T>(target: T, key: K, german: () => T[K] | undefined) {
  const english = target[key];
  Object.defineProperty(target, key, {
    enumerable: true,
    configurable: true,
    get: () => (lang() === 'de' ? (german() ?? english) : english),
  });
}

for (const guide of OPENING_GUIDES) {
  const de = () => OPENING_GUIDES_DE[guide.id];
  localize(guide, 'summary', () => de()?.summary);
  localize(guide, 'ideas', () => de()?.ideas);
  localize(guide, 'watchOut', () => de()?.watchOut);
  localize(guide, 'notes', () => de()?.notes);
  guide.traps?.forEach((trap, i) => {
    localize(trap, 'name', () => de()?.traps?.[i]?.name);
    localize(trap, 'note', () => de()?.traps?.[i]?.note);
  });
}
