// Builds src/engine/stockfishSource.ts: Stockfish.js 10, WebAssembly build, with the .wasm binary
// inlined (base64) so it runs from a Blob worker with no files to fetch — inside the phone
// WebView and on desktop alike. WebAssembly is several times faster than the old asm.js build,
// especially on iPhones (Safari's engine has no asm.js fast path).
//   node scripts/gen-stockfish.js
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '../node_modules/stockfish/src');
let js = fs.readFileSync(path.join(dir, 'stockfish.js'), 'utf8');
const wasm = fs.readFileSync(path.join(dir, 'stockfish.wasm')).toString('base64');
const hook = 'var Module={wasmBinaryFile:WasmPath};';
if (js.split(hook).length !== 2) throw new Error('stockfish.js changed: patch point not found');
// Hand the binary to Emscripten directly (it otherwise loads it with a sync XHR).
js = js.replace(hook, 'var Module={wasmBinaryFile:WasmPath||"inline.wasm",wasmBinary:self.__SF_WASM};');
const prefix = `self.__SF_WASM=(function(){var s=atob(${JSON.stringify(wasm)}),b=new Uint8Array(s.length);for(var i=0;i<s.length;i++)b[i]=s.charCodeAt(i);return b;})();\n`;
fs.writeFileSync(
  path.join(__dirname, '../src/engine/stockfishSource.ts'),
  '// Stockfish.js 10 (WebAssembly build, binary inlined) by Nathan Rugg et al. — GPLv3. https://github.com/nmrugg/stockfish.js\n' +
    '// Generated by scripts/gen-stockfish.js — do not edit.\n' +
    'export const STOCKFISH_SRC: string = ' + JSON.stringify(prefix + js) + ';\n',
);
console.log('ok', Math.round((prefix.length + js.length) / 1024), 'KB');
