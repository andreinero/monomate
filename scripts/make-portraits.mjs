// Generates the character portraits (PNG) from the Notionists illustration set by Zoish (CC0 1.0,
// https://heyzoish.gumroad.com/l/notionists) via DiceBear. Each character is a fixed combination of
// features, rendered in four moods.
// Run: node scripts/make-portraits.mjs   (macOS: uses Quick Look to rasterize the SVGs)
import { createAvatar } from '@dicebear/core';
import * as notionists from '@dicebear/notionists';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const OUT = path.resolve('assets/portraits');
const SIZE = 320;

const v = (n) => ['variant' + String(n).padStart(2, '0')];

/** Feature sets for every character (hair / glasses / beard / shirt icon). */
const CHARACTERS = {
  // Coaches
  sage: { hair: v(42), beard: v(2) },
  bolt: { hair: v(17), bodyIcon: ['electric'] },
  nova: { hair: v(20), glasses: v(3), bodyIcon: ['saturn'] },
  knox: { hair: v(49), beard: v(5), stern: true },
  // Bots
  pip: { hair: v(51) },
  rosa: { hair: v(8) },
  theo: { hair: v(44), beard: v(12) },
  juno: { hair: v(48), glasses: v(11) },
  marcus: { hair: v(22), beard: v(11) },
  ingrid: { hair: v(41), stern: true },
  kenji: { hair: v(53) },
  vex: { hair: v(26), glasses: v(1), stern: true },
  titan: { hair: v(32), glasses: v(6), bodyIcon: ['galaxy'] },
};

/** Mouth + eyebrows for each mood (picked from contact sheets). */
const MOODS = {
  neutral: { lips: v(17), brows: v(1), eyes: v(4) },
  happy: { lips: v(14), brows: v(4), eyes: v(4) },
  sad: { lips: v(18), brows: v(13), eyes: v(4) },
  surprised: { lips: v(15), brows: v(11), eyes: v(5) },
};

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'portraits-'));
fs.mkdirSync(OUT, { recursive: true });

const entries = [];
for (const [who, c] of Object.entries(CHARACTERS)) {
  for (const [mood, m] of Object.entries(MOODS)) {
    const svg = createAvatar(notionists, {
      seed: who,
      size: SIZE,
      scale: 128,
      translateY: 9,
      backgroundColor: ['f3f3f0'],
      body: v(1),
      nose: v(1),
      eyes: m.eyes,
      hair: c.hair,
      glasses: c.glasses ?? v(1),
      glassesProbability: c.glasses ? 100 : 0,
      beard: c.beard ?? v(1),
      beardProbability: c.beard ? 100 : 0,
      bodyIcon: c.bodyIcon ?? ['electric'],
      bodyIconProbability: c.bodyIcon ? 100 : 0,
      gestureProbability: 0,
      lips: m.lips,
      // Stern characters keep a flat brow unless they're surprised.
      brows: c.stern && mood === 'neutral' ? v(2) : m.brows,
    }).toString();
    const name = `${who}-${mood}`;
    const svgPath = path.join(tmp, `${name}.svg`);
    fs.writeFileSync(svgPath, svg);
    execFileSync('qlmanage', ['-t', '-s', String(SIZE), '-o', tmp, svgPath], { stdio: 'ignore' });
    fs.copyFileSync(path.join(tmp, `${name}.svg.png`), path.join(OUT, `${name}.png`));
    entries.push([who, mood, name]);
  }
}

// Hand-drawn characters: scripts/portraits-custom/<who>-<mood>.svg, rendered the same way.
const CUSTOM = path.resolve('scripts/portraits-custom');
const customFiles = fs.existsSync(CUSTOM) ? fs.readdirSync(CUSTOM) : [];
const customWho = [...new Set(customFiles.map((f) => f.match(/^(.+)-(\w+)\.svg$/)?.[1]).filter(Boolean))];
for (const who of customWho) {
  for (const mood of Object.keys(MOODS)) {
    const name = `${who}-${mood}`;
    const svgPath = path.join(CUSTOM, `${name}.svg`);
    if (!fs.existsSync(svgPath)) continue;
    execFileSync('qlmanage', ['-t', '-s', String(SIZE), '-o', tmp, svgPath], { stdio: 'ignore' });
    fs.copyFileSync(path.join(tmp, `${name}.svg.png`), path.join(OUT, `${name}.png`));
    entries.push([who, mood, name]);
  }
}

const byWho = {};
for (const [who, mood, name] of entries) (byWho[who] ??= []).push(`    ${mood}: require('../../assets/portraits/${name}.png'),`);
const ts =
  `// Generated by scripts/make-portraits.mjs — do not edit.\n` +
  `// Illustrations: Notionists by Zoish (CC0 1.0).\n` +
  `export const PORTRAITS = {\n` +
  Object.entries(byWho).map(([who, lines]) => `  ${who}: {\n${lines.join('\n')}\n  },`).join('\n') +
  `\n} as const;\n`;
fs.writeFileSync(path.resolve('src/assets/portraits.ts'), ts);
console.log('wrote', entries.length, 'portraits');
